    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String usuario = autenticar();
        if (usuario != null) {
            abrirAgenda(usuario);
        } else {
            mostrarError("Usuario o contraseña incorrectos");
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

    // Usuarios permitidos: la posición en usuarios[] coincide con la de claves[]
    private String[] usuarios = {"admin", "maria"};
    private String[] claves = {"1234", "5678"};

    // Devuelve el nombre del usuario si los datos son correctos, o null si no lo son
    public String autenticar() {
        String usuario = txtUsuario.getText().trim();
        String clave = new String(txtPassword.getPassword());
        for (int i = 0; i < usuarios.length; i++) {
            if (usuarios[i].equals(usuario) && claves[i].equals(clave)) {
                return usuario;
            }
        }
        return null;
    }

    // Abre la agenda de ese usuario (cada usuario tiene su propio archivo CSV)
    public void abrirAgenda(String usuario) {
        new VentanaAgenda(new GestorContactos(usuario)).setVisible(true);
        dispose();
    }

    public void mostrarError(String msg) {
        javax.swing.JOptionPane.showMessageDialog(this, msg, "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }


