    // Llena la tabla: llama getTipo() y getDetalle() sin saber qué subclase es (polimorfismo)
    public void actualizarTabla() {
        javax.swing.table.DefaultTableModel modelo
                = new javax.swing.table.DefaultTableModel(
                        new String[]{"Nombre", "Teléfono", "Email", "Tipo", "Detalle"}, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        int personales = 0, trabajo = 0;
        for (Contacto c : gestor.getContactos()) {
            modelo.addRow(new Object[]{c.getNombre(), c.getTelefono(),
                c.getEmail(), c.getTipo(), c.getDetalle()});
            if (c.getTipo().equals("Personal")) {
                personales++;
            } else {
                trabajo++;
            }
        }
        tablaContactos.setModel(modelo);
        tablaContactos.getColumnModel().getColumn(4).setPreferredWidth(300);   // columna Detalle más ancha
        lblTotal.setText("Personales: " + personales + "     Trabajo: " + trabajo
                + "     Total: " + gestor.getContactos().size());
    }

