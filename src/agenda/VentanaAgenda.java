    // Muestra solo los campos que corresponden al tipo elegido
    public void cambiarTipo() {
        boolean personal = "Personal".equals(comboTipo.getSelectedItem());
        lblCumpleanos.setVisible(personal);
        txtCumpleanos.setVisible(personal);
        lblEmpresa.setVisible(!personal);
        txtEmpresa.setVisible(!personal);
        lblPuesto.setVisible(!personal);
        txtPuesto.setVisible(!personal);
    }

    // Crea el contacto según el tipo elegido en el combo
    public Contacto leerFormulario() {
        String nombre = txtNombre.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String email = txtEmail.getText().trim();

        if ("Personal".equals(comboTipo.getSelectedItem())) {
            return new ContactoPersonal(nombre, telefono, email,
                    txtCumpleanos.getText().trim());
        }
        return new ContactoTrabajo(nombre, telefono, email,
                txtEmpresa.getText().trim(), txtPuesto.getText().trim());
    }

    // Valida campo por campo. Cada validador lanza una excepción si el dato está mal;
    // aquí se captura, se pinta el campo en rojo y se avisa al usuario.
    public boolean validarCampos() {
        limpiarMarcas();
        boolean personal = "Personal".equals(comboTipo.getSelectedItem());

        try {
            validarNombre(txtNombre.getText().trim());
        } catch (IllegalArgumentException ex) {
            marcarError(txtNombre, ex.getMessage());
            return false;
        }

        try {
            validarTelefono(txtTelefono.getText().trim());
        } catch (IllegalArgumentException ex) {
            marcarError(txtTelefono, ex.getMessage());
            return false;
        }

        try {
            validarEmail(txtEmail.getText().trim());
        } catch (IllegalArgumentException ex) {
            marcarError(txtEmail, ex.getMessage());
            return false;
        }

        if (personal) {
            try {
                validarCumpleanos(txtCumpleanos.getText().trim());
            } catch (IllegalArgumentException ex) {
                marcarError(txtCumpleanos, ex.getMessage());
                return false;
            }
        } else {
            try {
                validarEmpresa(txtEmpresa.getText().trim());
            } catch (IllegalArgumentException ex) {
                marcarError(txtEmpresa, ex.getMessage());
                return false;
            }

            try {
                validarPuesto(txtPuesto.getText().trim());
            } catch (IllegalArgumentException ex) {
                marcarError(txtPuesto, ex.getMessage());
                return false;
            }
        }
        return true;
    }

    // ---- Validadores: no devuelven nada, lanzan una excepción si hay error ----

    public void validarNombre(String texto) {
        if (texto.isEmpty()) {
            throw new IllegalArgumentException("El nombre es obligatorio");
        }
        if (!texto.matches("[a-zA-ZáéíóúÁÉÍÓÚñÑüÜ ]+")) {
            throw new IllegalArgumentException("El nombre solo debe contener letras");
        }
    }

    public void validarTelefono(String texto) {
        if (texto.isEmpty()) {
            throw new IllegalArgumentException("El teléfono es obligatorio");
        }
        if (!texto.matches("\\d+")) {
            throw new IllegalArgumentException("El teléfono solo debe contener números");
        }
        if (texto.length() < 7 || texto.length() > 10) {
            throw new IllegalArgumentException("El teléfono debe tener entre 7 y 10 dígitos");
        }
    }

    public void validarEmail(String texto) {
        if (texto.isEmpty()) {
            throw new IllegalArgumentException("El email es obligatorio");
        }
        if (!texto.matches("[\\w.+-]+@[\\w-]+(\\.[\\w-]+)+")) {
            throw new IllegalArgumentException("El email no es válido. Ejemplo: nombre@correo.com");
        }
    }

    // Formato obligatorio: dd/MM/aaaa (por ejemplo 25/12/1990), una fecha real y que ya haya pasado
    public void validarCumpleanos(String texto) {
        if (texto.isEmpty()) {
            throw new IllegalArgumentException("El cumpleaños es obligatorio");
        }
        java.time.LocalDate fecha;
        try {
            java.time.format.DateTimeFormatter formato = java.time.format.DateTimeFormatter
                    .ofPattern("dd/MM/uuuu").withResolverStyle(java.time.format.ResolverStyle.STRICT);
            fecha = java.time.LocalDate.parse(texto, formato);
        } catch (java.time.format.DateTimeParseException ex) {
            throw new IllegalArgumentException("El cumpleaños debe tener el formato dd/MM/aaaa y ser una fecha real. Ejemplo: 25/12/1990");
        }
        if (fecha.isAfter(java.time.LocalDate.now())) {
            throw new IllegalArgumentException("El cumpleaños no puede ser una fecha futura");
        }
        if (fecha.getYear() < 1900) {
            throw new IllegalArgumentException("El año del cumpleaños no es válido");
        }
    }

    public void validarEmpresa(String texto) {
        if (texto.isEmpty()) {
            throw new IllegalArgumentException("La empresa es obligatoria");
        }
        if (!texto.matches("[a-zA-Z0-9áéíóúÁÉÍÓÚñÑüÜ .&-]+")) {
            throw new IllegalArgumentException("La empresa solo puede tener letras, números y los símbolos . & -");
        }
    }

    public void validarPuesto(String texto) {
        if (texto.isEmpty()) {
            throw new IllegalArgumentException("El puesto es obligatorio");
        }
        if (!texto.matches("[a-zA-ZáéíóúÁÉÍÓÚñÑüÜ ]+")) {
            throw new IllegalArgumentException("El puesto solo debe contener letras");
        }
    }

